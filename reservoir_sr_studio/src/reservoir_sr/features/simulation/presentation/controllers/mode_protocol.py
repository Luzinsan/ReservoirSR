from __future__ import annotations


class DataModeController:
    """Базовый класс контроллера режима данных для playback-оркестратора.

    Все методы имеют no-op реализации по умолчанию.
    Контроллеры переопределяют только то, что им нужно.
    """

    def enter(self) -> None:
        """Переводит контроллер в активное состояние при входе в его вкладку."""

    def exit(self) -> None:
        """Переводит контроллер в неактивное состояние и очищает временные ресурсы."""

    def prepare(self) -> None:
        """Подготавливает ресурсы перед началом воспроизведения (инициализация, проверки)."""

    def step(self, step_count: int) -> bool:
        """Выполняет один playback-тик из `step_count` шагов. True — достигнут конец."""
        return True

    def pause(self) -> None:
        """Приостанавливает активный процесс контроллера (серверный job, симуляцию и т.д.)."""

    def cancel(self) -> None:
        """Отменяет активный процесс контроллера."""
